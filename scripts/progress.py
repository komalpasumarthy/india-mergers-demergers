#!/usr/bin/env python3
"""Regenerate PROGRESS.md from data/candidates.csv and data/events/*.json."""
import datetime as dt
import sys
from collections import Counter, defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from common import CANDIDATES, EVENTS_DIR, PROGRESS_MD, RAW, STATUSES, load_json, read_csv  # noqa


def scheme_status(rows):
    st = {r["status"] for r in rows}
    for s in ("in_progress", "pending", "detected", "complete", "skipped", "duplicate"):
        if st == {s}:
            return s
    if "in_progress" in st:
        return "in_progress"
    if "pending" in st:
        return "pending"
    if "detected" in st:
        return "detected"
    return "complete" if "complete" in st else sorted(st)[0]


def main():
    rows = read_csv(CANDIDATES)
    by_scheme = defaultdict(list)
    for r in rows:
        by_scheme[r["scheme"]].append(r)
    sch_status = {s: scheme_status(rs) for s, rs in by_scheme.items()}
    sc = Counter(sch_status.values())
    files = {p.stem: p for p in EVENTS_DIR.glob("*.json")}
    n_events = n_complete = 0
    for p in files.values():
        try:
            evs = load_json(p)["events"]
        except Exception:  # noqa: BLE001
            continue
        n_events += len(evs)
        n_complete += sum(e.get("status") == "complete" for e in evs)
    sources = Counter(v for r in rows for v in r["discovered_via"].split(";") if v)
    raw_files = sorted(p.name for p in RAW.glob("*.csv"))

    by_year = defaultdict(Counter)
    for s, st in sch_status.items():
        by_year[by_scheme[s][0]["year_hint"] or "?"][st] += 1

    done = sc["complete"] + sc["detected"] + sc["skipped"] + sc["duplicate"]
    total = len(by_scheme)
    out = [
        "# Progress",
        "",
        f"_Generated by `scripts/progress.py` on {dt.date.today().isoformat()}. Do not edit by hand._",
        "",
        "## Summary",
        "",
        f"- Candidate rows: **{len(rows)}** in **{total}** schemes",
        f"- Schemes researched: **{done} / {total}** ({(100 * done / total if total else 0):.0f}%)",
        f"- Events written: **{n_events}** ({n_complete} complete, {n_events - n_complete} detected)",
        "",
        "| scheme status | count |",
        "|---|---|",
    ]
    out += [f"| {s} | {sc.get(s, 0)} |" for s in STATUSES]
    out += ["", "## Discovery sources", "", "| source | candidate rows |", "|---|---|"]
    out += [f"| {k} | {v} |" for k, v in sources.most_common()]
    out += ["", "Raw listing files in `data/raw/`: " + (", ".join(f"`{f}`" for f in raw_files)
                                                         or "none yet")]
    out += ["", "## By year", "", "| year | " + " | ".join(STATUSES) + " |",
            "|---|" + "---|" * len(STATUSES)]
    for y in sorted(by_year, reverse=True):
        out.append(f"| {y} | " + " | ".join(str(by_year[y].get(s, 0)) for s in STATUSES) + " |")
    out += ["", "## Schemes", "", "| scheme | year | kind | source → counterparty | status | file | note |",
            "|---|---|---|---|---|---|---|"]
    for s in sorted(by_scheme, key=lambda s: (by_scheme[s][0]["year_hint"], s), reverse=True):
        rs = by_scheme[s]
        r0 = rs[0]
        desc = " + ".join(r["source_company"] for r in rs)
        desc = (desc[:70] + "…") if len(desc) > 70 else desc
        cp = (r0["counterparty"][:50] + "…") if len(r0["counterparty"]) > 50 else r0["counterparty"]
        f = f"[json](data/events/{s}.json)" if s in files else ""
        note = "; ".join(r["status_note"] for r in rs if r["status_note"])[:80]
        kinds = "/".join(sorted({r["kind_hint"] for r in rs}))
        out.append(f"| `{s}` | {r0['year_hint']} | {kinds} | {desc} → {cp} | {sch_status[s]} | {f} | "
                   f"{note.replace('|', '/')} |")
    PROGRESS_MD.write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"wrote {PROGRESS_MD.name}: {done}/{total} schemes researched")


if __name__ == "__main__":
    main()
